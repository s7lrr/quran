// الأقسام المناسبة لكل ساعة في الوضع الذكي
function autoKeys(hour, fri) {
  let keys;
  if (hour >= 3 && hour < 6) keys = ['fajr', 'work'];
  else if (hour >= 6 && hour < 9) keys = ['morning', 'work'];
  else if (hour >= 9 && hour < 11) keys = ['duha', 'work'];
  else if (hour >= 11 && hour < 15) keys = ['dhuhr', 'general'];
  else if (hour >= 15 && hour < 17) keys = ['asr', 'evening'];
  else if (hour >= 17 && hour < 20) keys = ['maghrib', 'evening'];
  else if (hour >= 20 && hour < 22) keys = ['isha', 'general'];
  else if (hour >= 22) keys = ['sleep'];
  else keys = ['qiyam'];
  if (fri && hour >= 6 && hour < 18) keys.push('friday');
  return keys;
}

